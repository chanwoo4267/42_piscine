#include <unistd.h>

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

void	print_nonprintable(unsigned char c)
{
	ft_putchar('\\');
	ft_putchar("0123456789abcdef"[c / 16]);
	ft_putchar("0123456789abcdef"[c % 16]);
}

void	ft_putstr_non_printable(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		if (str[i] <= 31 || str[i] == 127)
			print_nonprintable(str[i]);
		else
			ft_putchar(str[i]);
		i++;
	}
}
